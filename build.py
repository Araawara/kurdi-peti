#!/usr/bin/env python3
"""دروستکردنی پاکێجەکان لە سەرچاوە هاوبەشەکەوە (skills/kurdi-peti).

  python build.py

Outputs:
  skills/kurdi-peti/references/glossary.md   خشتەی فەرهەنگ بۆ خوێندنەوەی مۆدێل
  dist/kurdi-peti-skill.zip                  بۆ بارکردن لە Claude.ai
  dist/chatgpt/                              پەڕگەکانی Custom GPT
"""
import base64
import gzip
import json
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SKILL = ROOT / "skills" / "kurdi-peti"
REFS = SKILL / "references"
DIST = ROOT / "dist"
ORIGINS = {"ar": "عەرەبی", "fa": "فارسی", "tr": "تورکی", "en": "ئینگلیزی"}


def build_glossary_md():
    entries = json.loads((REFS / "glossary.json").read_text(encoding="utf-8"))["entries"]
    lines = [
        "# فەرهەنگی وشە بیانییەکان",
        "",
        "ئەم پەڕگەیە خۆکارانە لە glossary.json دروست دەکرێت. دەستکاری glossary.json بکە، نەک ئەمە.",
        "",
        "| ❌ وشەی بیانی | ✅ کوردیی پەتی | ڕەگ | ئاست |",
        "|---|---|---|---|",
    ]
    for e in sorted(entries, key=lambda e: (e["origin"], e["loan"])):
        loans = "، ".join([e["loan"], *e.get("variants", [])])
        level = "هەمیشە" if e["level"] == "core" else "توند"
        if e.get("review"):
            level += " (پێداچوونەوە)"
        lines.append(f"| {loans} | {'، '.join(e['pure'])} | {ORIGINS[e['origin']]} | {level} |")
    (REFS / "glossary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(entries)


def build_skill_zip():
    DIST.mkdir(exist_ok=True)
    out = DIST / "kurdi-peti-skill.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(SKILL.rglob("*")):
            if f.is_file() and "__pycache__" not in f.parts:
                z.write(f, Path("kurdi-peti") / f.relative_to(SKILL))
    return out


def build_chatgpt():
    out = DIST / "chatgpt"
    out.mkdir(parents=True, exist_ok=True)
    shutil.copy(ROOT / "chatgpt" / "instructions.md", out)
    for f in [REFS / "glossary.json", REFS / "rules.md", REFS / "software.md", SKILL / "scripts" / "check.py"]:
        shutil.copy(f, out)
    return out


def build_mcp():
    """Bundle the checker and data into mcp/api so the server has no file lookups at runtime."""
    api = ROOT / "mcp" / "api"
    shutil.copy(SKILL / "scripts" / "check.py", api / "kp_check.py")
    data = {
        "glossary": json.loads((REFS / "glossary.json").read_text(encoding="utf-8")),
        "docs": {name: (REFS / f"{name}.md").read_text(encoding="utf-8") for name in ("rules", "software")},
        "ui": [line.split("\t") for line in (REFS / "ui_terms.tsv").read_text(encoding="utf-8").splitlines()[3:] if line],
    }
    packed = base64.b64encode(gzip.compress(json.dumps(data, ensure_ascii=False).encode(), 9, mtime=0)).decode()
    (api / "kp_data.py").write_text(
        '"""Generated by build.py. Do not edit."""\n'
        "import base64, gzip, json\n\n"
        f'_DATA = json.loads(gzip.decompress(base64.b64decode("{packed}")))\n'
        'GLOSSARY = _DATA["glossary"]\nDOCS = _DATA["docs"]\nUI_TERMS = _DATA["ui"]\n', encoding="utf-8")
    return api


if __name__ == "__main__":
    n = build_glossary_md()
    print(f"glossary.md: {n} وشە")
    print(f"Claude skill: {build_skill_zip()}")
    print(f"ChatGPT:      {build_chatgpt()}")
    print(f"MCP server:   {build_mcp()}")
