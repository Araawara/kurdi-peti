class handler(BaseHTTPRequestHandler):
    def _send(self, status, body=b"", ctype="application/json"):
        self.send_response(status)
        self.send_header("Content-Type", f"{ctype}; charset=utf-8")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Headers", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _base(self):
        proto = self.headers.get("X-Forwarded-Proto", "http")
        return f"{proto}://{self.headers.get('Host', 'localhost')}"

    def do_OPTIONS(self):
        self._send(204)

    def do_GET(self):
        path = unquote(self.path.split("?")[0])
        if path.startswith("/word/"):
            loans, _ = find(path[len("/word/"):], limit=1)
            text = describe(loans[0]) if loans else "نەدۆزرایەوە"
            return self._send(200, text.encode(), "text/plain")
        if path.rstrip("/") == "/mcp":
            return self._send(405, b'{"error":"Use POST for MCP"}')
        # No auth: OAuth discovery (/.well-known/...) and unknown paths must 404,
        # otherwise clients try to register with a login service that does not exist.
        if path not in ("", "/"):
            return self._send(404, b'{"error":"Not found"}')
        self._send(200, HOME.format(base=self._base(), count=len(ENTRIES)).encode(), "text/html")

    def do_POST(self):
        if self.path.split("?")[0].rstrip("/") not in ("", "/mcp"):
            return self._send(404, b'{"error":"Not found"}')
        try:
            length = int(self.headers.get("Content-Length") or 0)
            payload = json.loads(self.rfile.read(length) or b"null")
        except (ValueError, json.JSONDecodeError):
            body = {"jsonrpc": "2.0", "id": None, "error": {"code": -32700, "message": "Parse error"}}
            return self._send(400, json.dumps(body).encode())
        base = self._base()
        REQUEST["oidc"] = self.headers.get("x-vercel-oidc-token")
        if isinstance(payload, list):
            replies = [r for r in (rpc(m, base) for m in payload) if r]
        else:
            replies = rpc(payload or {}, base)
        if not replies:
            return self._send(202)
        self._send(200, json.dumps(replies, ensure_ascii=False).encode())


