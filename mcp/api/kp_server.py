def norm(s):
    return s.translate(check.CHAR_MAP).replace("‌", "").strip()


def describe(e):
    loans = "، ".join([e["loan"], *e.get("variants", [])])
    line = f"«{loans}» ({ORIGINS.get(e['origin'], e['origin'])}) ← " + "، ".join(e["pure"])
    if e["level"] != "core":
        line += "  [ئاستی توند]"
    if e.get("review"):
        line += "  [پێداچوونەوەی دەوێت]"
    if e.get("note"):
        line += f"  ({e['note']})"
    return line


def find(query, limit=20):
    q = norm(query)
    if not q:
        return [], []
    exact = [e for rx, e in COMPILED if rx.fullmatch(q)]
    loans = exact or [e for e in ENTRIES if any(q in f for f in [e["loan"], *e.get("variants", [])])]
    pure = [e for e in ENTRIES if e not in loans and any(q in p for p in e["pure"])]
    return loans[:limit], pure[:limit]


