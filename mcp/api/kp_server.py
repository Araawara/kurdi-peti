def tool_search_word(args):
    loans, pure = find(args.get("word", ""))
    out = []
    if loans:
        out.append("وشەی بیانی:")
        out += ["- " + describe(e) for e in loans]
    if pure:
        out.append("ئەو وشە بیانییانەی کە ئەم وشە کوردییە جێگرەوەیانە:")
        out += ["- " + describe(e) for e in pure]
    if not out:
        out.append("لە فەرهەنگدا نییە. ئەگەر وشەیەکی کوردیی ڕەسەنە، بەکاری بهێنە. "
                   "ئەگەر بیانییە، لە ڕەگی کوردی جێگرەوەیەکی بۆ دابڕێژە (بڕوانە get_guide).")
    return "\n".join(out)


def tool_check_text(args):
    entries = check.compile_entries(ENTRIES, bool(args.get("core_only")))
    issues = check.check_text(args.get("text", ""), entries)
    if not issues:
        return "✓ هیچ کێشەیەک نەدۆزرایەوە. دەقەکە کوردیی پەتییە."
    lines = [f"ڕیز {i['line']}، ستوون {i['col']}: [{i['kind']}] «{i['word']}»  {i['message']}" for i in issues]
    errors = sum(i["kind"] == "هەڵە" for i in issues)
    lines.append(f"\nکۆی گشتی: {errors} هەڵە، {len(issues) - errors} پێشنیار.")
    return "\n".join(lines)


def tool_get_guide(args):
    topic = args.get("topic", "rules")
    if topic == "glossary":
        return "# فەرهەنگی وشە بیانییەکان\n\n" + "\n".join("- " + describe(e) for e in ENTRIES)
    return DOCS.get(topic) or DOCS["rules"]


def tool_search(args, base):
    loans, pure = find(args.get("query", ""), limit=10)
    results = [{"id": e["loan"], "title": describe(e), "url": f"{base}/word/{quote(e['loan'])}"} for e in loans + pure]
    return json.dumps({"results": results}, ensure_ascii=False)


def tool_fetch(args, base):
    wid = args.get("id", "")
    e = next((e for e in ENTRIES if e["loan"] == wid), None)
    if not e:
        return json.dumps({"id": wid, "title": "نەدۆزرایەوە", "text": "", "url": base}, ensure_ascii=False)
    return json.dumps({"id": wid, "title": e["loan"], "text": describe(e), "url": f"{base}/word/{quote(wid)}",
                       "metadata": {"origin": e["origin"], "level": e["level"]}}, ensure_ascii=False)


