def rpc(msg, base):
    """Handle one JSON-RPC message; return a response dict, or None for notifications."""
    method, mid, params = msg.get("method"), msg.get("id"), msg.get("params") or {}
    if mid is None:
        return None

    def ok(result):
        return {"jsonrpc": "2.0", "id": mid, "result": result}

    if method == "initialize":
        asked = params.get("protocolVersion")
        return ok({"protocolVersion": asked if asked in PROTOCOLS else PROTOCOLS[0],
                   "capabilities": {"tools": {"listChanged": False}},
                   "serverInfo": {**SERVER, "websiteUrl": base,
                                  "icons": [{"src": f"{base}/icon.png", "mimeType": "image/png", "sizes": ["512x512"]},
                                            {"src": f"{base}/icon.svg", "mimeType": "image/svg+xml"}]},
                   "instructions": INSTRUCTIONS})
    if method == "ping":
        return ok({})
    if method == "tools/list":
        return ok({"tools": TOOLS})
    if method == "tools/call":
        name, args = params.get("name"), params.get("arguments") or {}
        try:
            if name in HANDLERS:
                text = HANDLERS[name](args)
            elif name in NEEDS_BASE:
                text = NEEDS_BASE[name](args, base)
            else:
                return {"jsonrpc": "2.0", "id": mid, "error": {"code": -32602, "message": f"Unknown tool: {name}"}}
            return ok({"content": [{"type": "text", "text": text}], "isError": False})
        except Exception as exc:  # report tool failures to the model instead of crashing
            return ok({"content": [{"type": "text", "text": f"هەڵە: {exc}"}], "isError": True})
    return {"jsonrpc": "2.0", "id": mid, "error": {"code": -32601, "message": f"Method not found: {method}"}}


